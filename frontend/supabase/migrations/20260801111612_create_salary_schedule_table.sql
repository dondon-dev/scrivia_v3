/*
# Salary Schedule (DBM National Budget Circular)

## Overview
Stores the official Philippine government salary schedule (Salary Grade x Step matrix)
as published by the Department of Budget and Management (DBM) via National Budget
Circulars. The system uses this to auto-populate BASIC salary on employee records
based on their assigned salary grade and step.

## Schema
- tranche: which tranche of the salary schedule (e.g. "Third Tranche", "Fourth Tranche")
- circular_no: DBM circular reference (e.g. "NBC 601")
- effective_date: when the rates take effect
- grade: salary grade 1-33
- step: step 1-8 (SG 33 only has steps 1-2)
- monthly_salary: monthly basic salary in PHP

## Seed Data
Pre-loaded with the Third Tranche (NBC No. 601, effective January 1, 2026) salary
schedule from Annex A — 258 rows covering SG 1-32 (8 steps each) and SG 33 (2 steps),
pursuant to EO 64, s. 2024.

## Security
RLS enabled with full anon/authenticated CRUD so the browser client can read and
update the schedule when new DBM circulars are issued.
*/

CREATE TABLE IF NOT EXISTS salary_schedule (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tranche text NOT NULL DEFAULT 'Third Tranche',
  circular_no text NOT NULL DEFAULT 'NBC 601',
  effective_date date NOT NULL DEFAULT '2026-01-01',
  grade integer NOT NULL,
  step integer NOT NULL,
  monthly_salary numeric(14,2) NOT NULL,
  created_at timestamptz DEFAULT now(),
  UNIQUE (grade, step, tranche)
);

ALTER TABLE salary_schedule ENABLE ROW LEVEL SECURITY;

CREATE POLICY "select_salary_schedule" ON salary_schedule FOR SELECT
  TO anon, authenticated USING (true);
CREATE POLICY "insert_salary_schedule" ON salary_schedule FOR INSERT
  TO anon, authenticated WITH CHECK (true);
CREATE POLICY "update_salary_schedule" ON salary_schedule FOR UPDATE
  TO anon, authenticated USING (true) WITH CHECK (true);
CREATE POLICY "delete_salary_schedule" ON salary_schedule FOR DELETE
  TO anon, authenticated USING (true);

